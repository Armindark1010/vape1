export const getProduct = (id: string): Product | undefined =>
  PRODUCTS.find((p) => p.id === id)

export const relatedProducts = (id: string, count = 4): Product[] => {
  const current = getProduct(id)
  if (!current) return PRODUCTS.slice(0, count)
  const sameCat = PRODUCTS.filter((p) => p.id !== id && p.category === current.category)
  const rest = PRODUCTS.filter((p) => p.id !== id && p.category !== current.category)
  return [...sameCat, ...rest].slice(0, count)
}
